const assert = require('node:assert/strict');
const fs = require('node:fs');
const { validateLoadedCoupon } = require('../mobile/src/lib/coupon-load-validation.ts');
const { normalizeCouponCode } = require('../mobile/src/lib/coupon-code.ts');
const sport = (id, source = 'manual') => ({ uid: `sport-${id}`, kind: 'sport', matchId: id, matchSource: source, market: 'result', selection: 'home', odds: 1.5 });
const prediction = { uid: 'pred-1', kind: 'prediction', questionId: 1, market: 'prediction', selection: 'yes', odds: 1.7 };
assert.equal(validateLoadedCoupon([sport(1), sport(2), prediction], 30), null);
assert.match(validateLoadedCoupon([], 30), /aucune sélection/);
assert.match(validateLoadedCoupon([sport(1), sport(2)], 1), /limite/);
assert.match(validateLoadedCoupon([sport(1), sport(2, 'virtual')], 30), /mélange/);
assert.match(validateLoadedCoupon([sport(1), sport(1)], 30), /double/);
assert.match(validateLoadedCoupon([{ ...sport(1), odds: NaN }], 30), /invalide/);
assert.match(validateLoadedCoupon([{ ...sport(1), matchSource: undefined }], 30), /invalide/);
assert.equal(normalizeCouponCode('https://example.com/betslip?code=bx-84k2'), 'BX-84K2');
assert.equal(normalizeCouponCode('84k2'), 'BX-84K2');
const layout = fs.readFileSync('mobile/app/(main)/_layout.tsx', 'utf8');
const page = fs.readFileSync('mobile/app/(main)/betslip.tsx', 'utf8');
const actions = fs.readFileSync('mobile/src/components/betslip-coupon-actions.tsx', 'utf8');
assert(!layout.includes('ComboFloatingBar'));
assert(!page.includes('CouponCodeBox'));
assert(actions.includes('Alert.alert("Remplacer le coupon ?"'));
assert(!actions.includes('getLocalCachedCoupon'));
console.log('Coupon mobile : normalisation, limites, mélange, doublons et garde-fous OK');
