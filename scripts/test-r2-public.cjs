const assert = require('node:assert/strict');
const { inventory, contentType, isNotFound } = require('./r2-public.cjs');
const {normalizeAssetOrigin, publicAssetUrl, otaAssetUrl}=require('../src/lib/public-assets.ts');
const meta=require('../src/lib/expo-sdk52-meta.json');
const list=inventory();
assert(list.length>30);
assert(list.every(x => /^(images|brand|icons|expo-sdk52)\//.test(x.key) || /^(favicon\.ico|og-pulse-bet\.png|cashout\.mp3|crashed\.mp3|maintien\.mp3|Pulse-Bet-Android\.apk)$/.test(x.key)));
assert(!list.some(x => /\.env|\.json$|sw-static\.js|private/i.test(x.key)));
assert(list.some(x => '/'+x.key===meta.launchAsset.relativePath && x.immutable && x.type==='application/javascript'));
for(const a of meta.assets) assert(list.some(x => '/'+x.key===a.relativePath && x.type===a.contentType && x.immutable));
assert.equal(contentType('expo-sdk52/assets/abc',Buffer.from('89504e470d0a1a0a','hex')),'image/png');
assert.throws(()=>contentType('expo-sdk52/assets/abc',Buffer.from('unknown')));
assert(isNotFound({$metadata:{httpStatusCode:404}}));assert(!isNotFound({$metadata:{httpStatusCode:403}}));
assert.equal(normalizeAssetOrigin('https://cdn.example.com/'),'https://cdn.example.com');
for (const s of ['http://cdn.example.com','https://user:pass@cdn.example.com','https://cdn.example.com/path','https://cdn.example.com/?x=1','javascript:alert(1)']) assert.equal(normalizeAssetOrigin(s),null);
process.env.NEXT_PUBLIC_R2_PUBLIC_ORIGIN='https://cdn.example.com';
assert.equal(publicAssetUrl('/images/hero/test.webp'),'https://cdn.example.com/images/hero/test.webp');
assert.equal(publicAssetUrl('/api/wallet'),'/api/wallet');
assert.equal(publicAssetUrl('/images/../private'),' /images/../private'.trim());
assert.equal(otaAssetUrl(meta.launchAsset.relativePath,'https://app.example.com'),'https://app.example.com'+meta.launchAsset.relativePath);
process.env.R2_OTA_ASSETS_ORIGIN='https://cdn.example.com';
assert.equal(otaAssetUrl(meta.launchAsset.relativePath,'https://app.example.com'),'https://cdn.example.com'+meta.launchAsset.relativePath);
assert.throws(()=>otaAssetUrl('/api/wallet','https://app.example.com'));
console.log(`R2 public : ${list.length} objets autorisés, MIME, origines et repli OTA vérifiés.`);
