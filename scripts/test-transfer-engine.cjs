const assert = require('node:assert/strict');
const fs = require('node:fs');
const Module = require('node:module');
const { PGlite } = require('@electric-sql/pglite');
const { drizzle } = require('drizzle-orm/pglite');
const original = Module._load;
(async () => {
  const pg = new PGlite();
  await pg.exec(`CREATE TABLE app_user(id integer primary key, balance float8 not null, bonus_locked float8 not null default 0, currency text not null);
    CREATE TABLE admin_settings(setting_key text primary key, value jsonb, updated_at timestamp);
    CREATE TABLE bets(user_id integer, stake float8, odds float8, status text);
    CREATE TABLE prediction_bets(user_id integer, stake float8, odds float8, status text);
    CREATE TABLE combo_bets(user_id integer, stake float8, total_odds float8, status text);
    INSERT INTO app_user VALUES (1,100,20,'EUR'),(2,10,0,'EUR'),(3,10,0,'EUR'),(4,10,0,'EUR');`);
  const db = drizzle(pg);
  Module._load = function(name) { if (name === '@/db') return {db}; return original.apply(this,arguments); };
  const { ensureTransferSchema } = require('../src/db/transfer-schema.ts');
  await Promise.all([ensureTransferSchema(), ensureTransferSchema()]);
  await pg.exec(fs.readFileSync('migrations/transfer-codes.sql','utf8'));
  const {createTransfer,redeemTransfer,cancelTransfer} = require('../src/lib/transfer-code-engine.ts');
  const secret = 'ac'.repeat(32);
  const key = i => `operation-${String(i).padStart(12,'0')}`;
  await assert.rejects(createTransfer(1, 81, key(1), secret), /insuffisant/);
  const a = await createTransfer(1, 30, key(1), secret);
  assert.equal(a.balance,70); assert.match(a.code,/^\d{20}$/);
  const repeat = await createTransfer(1,30,key(1),secret); assert.equal(repeat.code,null); assert.equal(repeat.id,a.id);
  await assert.rejects(createTransfer(1,40,key(1),secret), /autre montant/);
  let r = await redeemTransfer(2,a.code,key(2),secret); assert.equal(r.kind,'ok'); assert.equal(r.balance,40);
  r = await redeemTransfer(2,a.code,key(2),secret); assert.equal(r.duplicate,true); assert.equal(r.balance,40);
  assert.equal((await redeemTransfer(3,a.code,key(3),secret)).kind,'invalid');
  assert.equal((await cancelTransfer(1,a.id)).kind,'invalid');
  const b = await createTransfer(1,10,key(4),secret);
  const refund = await cancelTransfer(1,b.id); assert.equal(refund.balance,70);
  assert.equal((await cancelTransfer(1,b.id)).duplicate,true);
  assert.equal((await redeemTransfer(3,b.code,key(5),secret)).kind,'invalid');
  for (let i=0;i<3;i++) assert.equal((await redeemTransfer(3,'wrong',key(6+i),secret)).kind,'invalid');
  assert.equal((await redeemTransfer(3,'wrong',key(10),secret)).kind,'blocked');
  // Appels concurrents sur base isolée : une seule opération doit gagner.
  const c = await createTransfer(1, 10, key(30), secret);
  const results = await Promise.all([redeemTransfer(2,c.code,key(31),secret), cancelTransfer(1,c.id)]);
  assert.equal(results.filter(x => x.kind === 'ok').length, 1);
  const d = await createTransfer(1, 10, key(32), secret);
  const two = await Promise.all([redeemTransfer(2,d.code,key(33),secret), redeemTransfer(4,d.code,key(34),secret)]);
  assert.equal(two.filter(x => x.kind === 'ok').length, 1);
  const e = await createTransfer(1, 10, key(35), secret);
  assert.equal((await redeemTransfer(2,e.code,key(33),secret)).kind,'invalid');
  assert.equal((await cancelTransfer(1,e.id)).kind,'ok');
  const balanceTotal = await pg.query('SELECT sum(balance)::float8 AS total FROM app_user');
  assert.equal(balanceTotal.rows[0].total, 130);
  const audit = await pg.query('SELECT action,count(*)::int AS n FROM transfer_code_audit GROUP BY action');
  assert(audit.rows.some(x => x.action==='redeemed' && x.n>=2));
  const saved = await pg.query('SELECT code_hash FROM transfer_codes');
  assert(!JSON.stringify(saved.rows).includes(a.code));
  await pg.close();
  console.log('Transferts : débit, bonus, usage unique, idempotence, annulation, blocage et audit OK sur PGlite isolé');
})().catch(e => {console.error(e); process.exitCode=1;});
